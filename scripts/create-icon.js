// Simple script to create a placeholder 256x256 PNG icon
const fs = require('fs');
const path = require('path');

// Create a minimal valid PNG file (1x1 transparent pixel)
// We'll use this as a placeholder since we don't have image processing libraries
const minimalPNG = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
  0x00, 0x00, 0x00, 0x0D, // IHDR chunk length
  0x49, 0x48, 0x44, 0x52, // "IHDR"
  0x00, 0x00, 0x01, 0x00, // Width: 256
  0x00, 0x00, 0x01, 0x00, // Height: 256
  0x08, 0x06, 0x00, 0x00, 0x00, // Bit depth, color type, etc.
  0x5C, 0x72, 0xA8, 0x66, // CRC
  0x00, 0x00, 0x00, 0x01, // IDAT chunk length
  0x49, 0x44, 0x41, 0x54, // "IDAT"
  0x08, 0xD7, 0x63, 0x60, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01,
  0xE2, 0x21, 0xBC, 0x33, // Minimal image data + CRC
  0x00, 0x00, 0x00, 0x00, // IEND chunk length
  0x49, 0x45, 0x4E, 0x44, // "IEND"
  0xAE, 0x42, 0x60, 0x82  // CRC
]);

const iconPath = path.join(__dirname, '..', 'assets', 'icon.png');
fs.writeFileSync(iconPath, minimalPNG);
console.log('Created placeholder icon at:', iconPath);
